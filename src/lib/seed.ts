export function seedReferenceData(db: DatabaseSync) {
  db.exec("BEGIN IMMEDIATE");
  try {
    seed(db);
    db.exec("COMMIT");
  } catch (e) {
    db.exec("ROLLBACK");
    throw e;
  }
}

function seed(db: DatabaseSync) {
  const hasLeave = db.prepare("SELECT COUNT(*) AS c FROM leave_types").get() as { c: number };
  if (Number(hasLeave.c) === 0) {
    const st = db.prepare(
      "INSERT OR IGNORE INTO leave_types(code, name, default_days, paid, full_cycle, deducts_balance, legal_reference) VALUES (?,?,?,?,?,?,?)",
    );
    for (const l of LEAVE_TYPES) st.run(...l);
  }
  const hasVio = db.prepare("SELECT COUNT(*) AS c FROM violation_types").get() as { c: number };
  if (Number(hasVio.c) === 0) {
    const st = db.prepare(
      "INSERT OR IGNORE INTO violation_types(code, category, description, penalty1, penalty2, penalty3, penalty4) VALUES (?,?,?,?,?,?,?)",
    );
    for (const v of VIOLATIONS) st.run(...v);
  }
  const defaults: Record<string, string> = {
    deduction_basis: "total",          // total | basic : أساس حساب خصم التأخير
    block_shared_device: "1",          // منع تسجيل حضور من جهاز مستخدم لموظف آخر
    require_selfie: "1",
    overtime_rate_basic_pct: "50",     // المادة 107: أجر الساعة + 50% من الأجر الأساسي
    violation_repeat_days: "180",      // مدة احتساب التكرار
    max_violation_days: "5",           // الحد الأقصى للخصم عن المخالفة الواحدة (أيام)
  };
  const ins = db.prepare("INSERT OR IGNORE INTO settings(key, value) VALUES (?, ?)");
  for (const [k, v] of Object.entries(defaults)) ins.run(k, v);
}
